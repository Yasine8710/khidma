List<ProfessionalSummary> buildDemoProfessionals() {
  return [
    for (var i = 0; i < _pros.length; i++)
      () {
        final p = _pros[i];
        final c = demoCityCentre(p.$3);
        final city = demoCities[p.$3 - 1];
        return ProfessionalSummary(
          id: 'demo-${(i + 1).toString().padLeft(2, '0')}',
          name: p.$1,
          categoryId: p.$2,
          description: p.$9,
          yearsExperience: p.$8,
          governorateId: city.governorateId,
          cityId: city.id,
          latitude: c.lat,
          longitude: c.lng,
          availability: p.$6,
          verification: p.$7 ? Verification.verified : Verification.unverified,
          rating: p.$4,
          reviewCount: p.$5,
        );
      }(),
  ];
}
